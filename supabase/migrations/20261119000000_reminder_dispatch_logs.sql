CREATE TABLE IF NOT EXISTS public.reminder_dispatch_logs (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id INT REFERENCES public.cycles(id) ON DELETE SET NULL,
  type TEXT NOT NULL,
  slot TEXT,
  user_id INT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  user_name TEXT,
  target_date DATE NOT NULL,
  title TEXT,
  body TEXT,
  status TEXT NOT NULL,
  status_code INT,
  error_message TEXT,
  endpoint TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_reminder_dispatch_logs_cycle_id ON public.reminder_dispatch_logs(cycle_id);
CREATE INDEX IF NOT EXISTS idx_reminder_dispatch_logs_user_id ON public.reminder_dispatch_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_reminder_dispatch_logs_created_at ON public.reminder_dispatch_logs(created_at DESC);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.reminder_dispatch_logs TO anon, authenticated, service_role;
GRANT ALL ON SEQUENCE public.reminder_dispatch_logs_id_seq TO service_role;
