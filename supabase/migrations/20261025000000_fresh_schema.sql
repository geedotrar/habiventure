-- Users
CREATE TABLE public.users (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL,
  pin_hash VARCHAR(255) NOT NULL,
  phone VARCHAR(20) NOT NULL DEFAULT '',
  gender VARCHAR(10) NOT NULL DEFAULT 'male' CHECK (gender IN ('male', 'female')),
  role VARCHAR(15) NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'superadmin')),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_users_active ON public.users (active);
CREATE INDEX idx_users_role ON public.users (role);

-- Pairs
CREATE TABLE public.pairs (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_1_id INT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  user_2_id INT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT check_different_pair_users CHECK (user_1_id <> user_2_id),
  CONSTRAINT unique_pair_members UNIQUE (user_1_id, user_2_id)
);

CREATE INDEX idx_pairs_users ON public.pairs (user_1_id, user_2_id);
CREATE INDEX idx_pairs_user_2_id ON public.pairs (user_2_id);
CREATE INDEX idx_pairs_active ON public.pairs (active);

-- Tasks
CREATE TABLE public.tasks (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  base_score SMALLINT NOT NULL DEFAULT 10,
  frequency VARCHAR(15) NOT NULL DEFAULT 'daily' CHECK (frequency IN ('daily', 'weekly_2x', 'weekly_custom', 'cycle')),
  target_days_per_week SMALLINT NOT NULL DEFAULT 7 CHECK (target_days_per_week BETWEEN 1 AND 7),
  is_personal BOOLEAN NOT NULL DEFAULT FALSE,
  created_by INT REFERENCES public.users(id) ON DELETE SET NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_tasks_created_by ON public.tasks (created_by);
CREATE INDEX idx_tasks_active ON public.tasks (active);
CREATE INDEX idx_tasks_personal_active ON public.tasks (is_personal, active);
CREATE INDEX idx_tasks_frequency ON public.tasks (frequency);

-- Cycles
CREATE TABLE public.cycles (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('draft', 'active', 'closed')),
  winner_user_id INT REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_cycles_status ON public.cycles (status);
CREATE INDEX idx_cycles_winner_user_id ON public.cycles (winner_user_id);

-- Daily Logs
CREATE TABLE public.daily_logs (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date DATE NOT NULL,
  user_id INT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  task_id INT NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  status VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'completed', 'missed')),
  completed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT unique_daily_user_task UNIQUE (date, user_id, task_id)
);

CREATE INDEX idx_daily_logs_task_id ON public.daily_logs (task_id);
CREATE INDEX idx_daily_logs_user_task ON public.daily_logs (user_id, task_id);
CREATE INDEX idx_daily_logs_user_date ON public.daily_logs (user_id, date DESC);
CREATE INDEX idx_daily_logs_user_status ON public.daily_logs (user_id, status);
CREATE INDEX idx_daily_logs_date ON public.daily_logs (date DESC);

-- Score Events
CREATE TABLE public.score_events (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id INT NOT NULL REFERENCES public.cycles(id) ON DELETE CASCADE,
  user_id INT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  date DATE NOT NULL,
  type VARCHAR(30) NOT NULL,
  points SMALLINT NOT NULL,
  reason VARCHAR(255) NOT NULL,
  metadata JSONB DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_score_events_cycle_user ON public.score_events (cycle_id, user_id);
CREATE INDEX idx_score_events_user_id ON public.score_events (user_id);
CREATE INDEX idx_score_events_lookup ON public.score_events (cycle_id, user_id, date, type);
CREATE INDEX idx_score_events_cycle_created ON public.score_events (cycle_id, created_at ASC);

-- Punishments
CREATE TABLE public.punishments (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_punishments_active ON public.punishments (active);

-- Cycle Results
CREATE TABLE public.cycle_results (
  cycle_id INT PRIMARY KEY REFERENCES public.cycles(id) ON DELETE CASCADE,
  winner_user_id INT REFERENCES public.users(id) ON DELETE SET NULL,
  loser_user_id INT REFERENCES public.users(id) ON DELETE SET NULL,
  winner_score INT NOT NULL DEFAULT 0,
  loser_score INT NOT NULL DEFAULT 0,
  score_diff INT NOT NULL DEFAULT 0,
  selected_punishment_id INT REFERENCES public.punishments(id) ON DELETE SET NULL,
  closed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_cycle_results_winner ON public.cycle_results (winner_user_id);
CREATE INDEX idx_cycle_results_loser ON public.cycle_results (loser_user_id);
CREATE INDEX idx_cycle_results_punishment ON public.cycle_results (selected_punishment_id);

-- Decision Wheel Options
CREATE TABLE public.decision_wheel_options (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


